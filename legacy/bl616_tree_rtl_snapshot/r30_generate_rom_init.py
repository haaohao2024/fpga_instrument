from pathlib import Path
import hashlib
S=Path(__file__).resolve().parent
def words(n):return [int(v,16) for v in (S/n).read_text().split()]
def emit(name,values,width,per,sources):
 assert len(values)==64*per
 lines=["// Generated by r30_generate_rom_init.py; regenerate after editing source ROMs."]
 for n in sources:lines.append("// "+n+" SHA256 "+hashlib.sha256((S/n).read_bytes()).hexdigest())
 for i in range(64):
  n=sum(v<<(width*j) for j,v in enumerate(values[i*per:(i+1)*per]))
  lines.append(f"   .INIT_RAM_{i:02X}({width*per}'h{n:0{width*per//4}x})"+("," if i<63 else ""))
 (S/name).write_text("\n".join(lines)+"\n")
cos=words('visual_cos_q16.mem');font=words('visual_font.mem');labels=words('visual_labels.mem')
assert len(cos)==1024 and len(font)==1024 and len(labels)==2048
packed=[0]*1024
for row in range(42):
 for col in range(24):packed[row*24+col]=labels[row*32+col]
emit('r30_cosine_init.vh',cos,18,16,['visual_cos_q16.mem'])
emit('r30_text_init.vh',packed+font,8,32,['visual_labels.mem','visual_font.mem'])
